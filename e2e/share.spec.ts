import { expect, test } from '@playwright/test'
import { buyEtf, collectProblems, createPortfolio, expectNoOverflow, register } from './helpers/app'

test('Freigabe: Link erstellen, annehmen, nur lesen, widerrufen', async ({ browser, page }) => {
  const problems = collectProblems(page)
  await register(page, { name: 'Anna' })
  const depotId = await createPortfolio(page, 'Kinderdepot')
  await buyEtf(page, '2', '256,90')

  const shares = page.getByRole('region', { name: 'Freigaben' })
  await shares.getByRole('button', { name: 'Link zum Teilen erstellen' }).click()
  const link = await shares.getByLabel(/Link zum Weitergeben/).inputValue()
  expect(link).toMatch(/\/app\/freigabe\/[A-Za-z0-9_-]{43}$/)
  // eigener Link ist für den Besitzer ungültig
  await page.goto(link)
  await expect(page.getByText(/gehört zu deinem eigenen Depot/)).toBeVisible()

  // Bob nimmt an (eigener Browser-Kontext)
  const bobContext = await browser.newContext()
  const bob = await bobContext.newPage()
  await register(bob, { name: 'Bob' })
  await bob.goto(link)
  await expect(bob.getByRole('heading', { name: 'Depot ansehen?' })).toBeVisible()
  await expect(bob.getByText(/Anna teilt das Depot „Kinderdepot“ mit dir/)).toBeVisible()
  await bob.getByRole('button', { name: 'Annehmen' }).click()
  await bob.waitForURL(new RegExp(`/app/geteilt/${depotId}$`))
  await expect(bob.getByText(/Geteilt von Anna · Wertpapierdepot · nur lesen/)).toBeVisible()
  await expect(bob.getByRole('table', { name: 'Positionen in Kinderdepot' })).toContainText('Vanguard')
  await expect(bob.getByRole('button', { name: 'Buchung speichern' })).toHaveCount(0)
  await expectNoOverflow(bob)
  // das Original-Depot (Besitzerseite) bleibt für Bob unsichtbar
  const ownerPage = await bob.goto(`/app/depots/${depotId}`)
  expect(ownerPage?.status()).toBe(404)
  await bob.goto('/app/depots')
  await expect(bob.getByRole('region', { name: 'Mit mir geteilt' })).toContainText('Kinderdepot')
  // Link ist verbraucht
  await bob.goto(link)
  await expect(bob.getByText(/ungültig, abgelaufen, wurde schon verwendet/)).toBeVisible()

  // Anna sieht die Freigabe und widerruft sie
  await page.goto(`/app/depots/${depotId}`)
  await expect(shares.getByText('Bob')).toBeVisible()
  await shares.getByRole('button', { name: 'Freigabe für Bob widerrufen' }).click()
  await expect(shares.getByText('Freigabe widerrufen.')).toBeVisible()
  const after = await bob.goto(`/app/geteilt/${depotId}`)
  expect(after?.status()).toBe(404)
  await bobContext.close()
  expect(problems).toEqual([])
})

test('Ziel teilen: ansehen und mitbearbeiten, nur Planwerte, widerrufen', async ({ browser, page }) => {
  const problems = collectProblems(page)
  await register(page, { name: 'Anna' })
  await createPortfolio(page, 'Tagesgeld', 'cash')
  await page.getByLabel('Art', { exact: true }).selectOption('deposit')
  await page.getByLabel(/^Betrag/).fill('2.500,00')
  await page.getByRole('button', { name: 'Buchung speichern' }).click()
  await expect(page.getByText('Buchung gespeichert.')).toBeVisible()

  await page.goto('/app/road')
  const form = page.getByRole('region', { name: 'Neues Ziel' })
  await form.getByLabel('Name').fill('Urlaub')
  await form.getByLabel('Zielbetrag in €').fill('10.000')
  await form.getByLabel('Nur ausgewählte').check()
  await form.getByLabel('Tagesgeld').check()
  await form.getByRole('button', { name: 'Ziel anlegen' }).click()
  const goals = page.getByRole('region', { name: 'Eigene Ziele' })
  await expect(goals).toContainText('Urlaub')

  // Link mit Recht „mitbearbeiten“
  await goals.getByRole('button', { name: 'Teilen' }).click()
  await goals.getByLabel('Ansehen und mitbearbeiten').check()
  await goals.getByRole('button', { name: 'Link zum Teilen erstellen' }).click()
  const link = await goals.getByLabel(/Link zum Weitergeben/).inputValue()
  expect(link).toMatch(/\/app\/road\/freigabe\/[A-Za-z0-9_-]{43}$/)
  await expect(goals).toContainText(/Offener Link\s*mitbearbeiten/)

  const bobContext = await browser.newContext()
  const bob = await bobContext.newPage()
  const bobProblems = collectProblems(bob)
  await register(bob, { name: 'Bob' })
  await bob.goto(link)
  await expect(bob.getByRole('heading', { name: 'Ziel mitbearbeiten?' })).toBeVisible()
  await expect(bob.getByText(/Anna teilt das Ziel „Urlaub“ mit dir/)).toBeVisible()
  await bob.getByRole('button', { name: 'Annehmen' }).click()
  await bob.waitForURL(/\/app\/road#geteilte-ziele$/)
  const shared = bob.getByRole('region', { name: 'Mit mir geteilt' })
  await expect(shared).toContainText('Von Anna geteilt · mitbearbeiten')
  await expect(shared).toContainText(/2\.500\s€ von 10\.000\s€/)
  await expect(shared).toContainText('Tagesgeld')
  // Bobs eigene Ziele bleiben leer, Annas Konto erscheint nicht als eigenes
  await expect(bob.getByRole('region', { name: 'Eigene Ziele' })).toContainText('Noch keine eigenen Ziele')
  await bob.goto('/app/depots')
  await expect(bob.getByText('Tagesgeld')).toHaveCount(0)

  // Bob ändert den Betrag – die Depot-Auswahl gibt es für ihn nicht
  await bob.goto('/app/road')
  await shared.getByRole('button', { name: 'Bearbeiten' }).click()
  await expect(shared.getByText('Was zählt')).toHaveCount(0)
  await shared.getByLabel('Zielbetrag in €').fill('5.000')
  await shared.getByRole('button', { name: 'Ziel speichern' }).click()
  await expect(shared).toContainText('50 %')
  await expectNoOverflow(bob)

  // Anna sieht die Änderung, die Freigabe und den Eintrag unter „Aktivität“
  await page.goto('/app/road')
  await expect(goals).toContainText(/2\.500\s€ von 5\.000\s€/)
  await expect(goals).toContainText('Geteilt mit 1 Person')
  await page.goto('/app/sicherheit')
  await expect(page.locator('section', { has: page.getByRole('heading', { name: 'Aktivität' }) })).toContainText('Ziel über eine Freigabe geändert')

  // Widerrufen beendet den Zugriff sofort
  await page.goto('/app/road')
  await goals.getByRole('button', { name: 'Teilen' }).click()
  await goals.getByRole('button', { name: 'Freigabe für Bob widerrufen' }).click()
  await expect(goals.getByText('Freigabe widerrufen.')).toBeVisible()
  await bob.goto('/app/road')
  await expect(bob.getByRole('region', { name: 'Mit mir geteilt' })).toHaveCount(0)
  await bobContext.close()
  expect(problems).toEqual([])
  expect(bobProblems).toEqual([])
})

test('Ziel nur zum Ansehen: kein Bearbeiten, Verlassen möglich', async ({ browser, page }) => {
  await register(page, { name: 'Anna' })
  await createPortfolio(page, 'Konto', 'cash')
  await page.goto('/app/road')
  const form = page.getByRole('region', { name: 'Neues Ziel' })
  await form.getByLabel('Name').fill('Auto')
  await form.getByLabel('Zielbetrag in €').fill('20.000')
  await form.getByRole('button', { name: 'Ziel anlegen' }).click()
  const goals = page.getByRole('region', { name: 'Eigene Ziele' })
  await goals.getByRole('button', { name: 'Teilen' }).click()
  await expect(goals.getByText(/ist das dein Gesamtvermögen/)).toBeVisible()
  await goals.getByRole('button', { name: 'Link zum Teilen erstellen' }).click()
  const link = await goals.getByLabel(/Link zum Weitergeben/).inputValue()

  const bobContext = await browser.newContext()
  const bob = await bobContext.newPage()
  await register(bob, { name: 'Bob' })
  await bob.goto(link)
  await expect(bob.getByRole('heading', { name: 'Ziel ansehen?' })).toBeVisible()
  await bob.getByRole('button', { name: 'Annehmen' }).click()
  const shared = bob.getByRole('region', { name: 'Mit mir geteilt' })
  await expect(shared).toContainText('Von Anna geteilt · ansehen')
  await expect(shared).toContainText('Alle Depots und Konten')
  await expect(shared.getByRole('button', { name: 'Bearbeiten' })).toHaveCount(0)
  await shared.getByRole('button', { name: 'Freigabe verlassen' }).click()
  await shared.getByRole('button', { name: 'Ja, verlassen' }).click()
  await expect(bob.getByRole('region', { name: 'Mit mir geteilt' })).toHaveCount(0)
  await bobContext.close()
})
